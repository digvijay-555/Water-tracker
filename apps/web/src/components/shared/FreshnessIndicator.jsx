import React from 'react';

/**
 * Calculates human-readable relative time and staleness classification.
 */
function getFreshnessDetails(isoString) {
  if (!isoString) {
    return { label: 'No update', isStale: true, timeAgo: 'Unknown' };
  }

  const updateTime = new Date(isoString).getTime();
  const diffMs = Date.now() - updateTime;
  const diffMinutes = Math.floor(diffMs / (1000 * 60));
  const diffHours = Math.floor(diffMinutes / 60);

  if (diffMinutes < 1) {
    return { label: 'Live (Just now)', isStale: false, timeAgo: 'Just now' };
  }
  if (diffMinutes < 60) {
    return { label: `${diffMinutes}m ago`, isStale: false, timeAgo: `${diffMinutes} mins ago` };
  }
  if (diffHours < 4) {
    return { label: `${diffHours}h ago`, isStale: false, timeAgo: `${diffHours} hours ago` };
  }
  if (diffHours < 24) {
    return { label: `Stale (${diffHours}h ago)`, isStale: true, timeAgo: `${diffHours} hours ago` };
  }
  const days = Math.floor(diffHours / 24);
  return { label: `Stale (${days}d ago)`, isStale: true, timeAgo: `${days} days ago` };
}

export function FreshnessIndicator({ timestamp, source = 'SIMULATED', showSourceBadge = true }) {
  const { label, isStale, timeAgo } = getFreshnessDetails(timestamp);

  return (
    <div className="freshness-indicator-wrapper">
      <span
        className={`freshness-indicator ${isStale ? 'freshness-stale' : 'freshness-live'}`}
        title={`Last location report: ${new Date(timestamp).toLocaleString()} (${timeAgo})`}
      >
        <span className="freshness-icon">{isStale ? '⚠️' : '📍'}</span>
        <span>{label}</span>
      </span>

      {showSourceBadge && (
        <span
          className="freshness-source-tag"
          title={source === 'SIMULATED' ? 'Location coordinates generated by demonstration simulation' : 'Location reported by device'}
        >
          {source}
        </span>
      )}
    </div>
  );
}

export default FreshnessIndicator;
